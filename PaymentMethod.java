/**
 * Рівень 1: поведінка, що ВІДРІЗНЯЄТЬСЯ залежно від способу оплати замовлення.
 * Кожна реалізація по-своєму списує гроші.
 */
public interface PaymentMethod {

    /**
     * Намагається оплатити суму.
     *
     * @return скільки грн реально покрито ЦИМ способом оплати
     *         (картка/готівка покривають усю суму, гаманець — лише в межах бонусів)
     */
    double pay(double amount);

    /** Коротка назва способу оплати (для заголовка та повідомлень). */
    String getLabel();

    /**
     * Рівень 2: default-метод — реалізація «за замовчуванням».
     * CardPayment і CashPayment успадковують її без змін,
     * WalletPayment — перевизначає (додає залишок бонусів).
     */
    default void printPaymentHeader(String customerName) {
        System.out.println("Оплата для " + customerName + " через: " + getLabel());
    }
}
